import {
  aliasedName,
  buildLineage,
  publicRoleName,
  publicSystemName,
  type Lineage,
  type ResolvedDefinition,
  type ResolvedRef,
  type ResolvedRole,
  type ResolvedStep,
  type ResolvedSystem,
} from "./resolve.js";

/**
 * `plain` emits primitives into `:root`, usable by any stylesheet.
 * `tailwind` wraps them in `@theme` and adds the `@theme inline` utility
 * wiring — correct inside a Tailwind v4 build, and inert anywhere else,
 * since a browser discards an at-rule it does not know.
 */
export type CssFormat = "plain" | "tailwind";

export const CSS_FORMATS: CssFormat[] = ["plain", "tailwind"];

function cssVarName(role: ResolvedRole): string {
  return publicRoleName(role, "css", "-");
}

function cssValueFor(resolved: ResolvedDefinition, entry: ResolvedRef): string {
  if (entry.target.kind === "step" && entry.opaque) {
    const system = resolved.systems.find(
      (s) => entry.target.kind !== "role" && s.system === entry.target.system,
    );
    const step = system?.steps.find(
      (s) => entry.target.kind !== "role" && s.selector === entry.target.selector,
    );
    if (system && step) {
      return `var(--color-${publicSystemName(system, "css")}-${step.publicStep})`;
    }
  }
  if (entry.target.kind === "role") {
    const target = resolved.roles.find(
      (r) =>
        entry.target.kind === "role" &&
        r.domain === entry.target.domain &&
        r.role === entry.target.role,
    );
    if (target) return `var(--${cssVarName(target)})`;
  }
  // transparent() results and overlay steps have no primitive variable to
  // point at; they inline their computed value.
  return entry.css;
}

export function emitCss(
  resolved: ResolvedDefinition,
  format: CssFormat = "plain",
): string {
  const lines: string[] = [];
  lines.push(
    "/* Generated by dtg from the definition file — do not edit. */",
    "",
    format === "tailwind" ? "@theme {" : ":root {",
  );
  for (const system of resolved.systems) {
    const opaqueSteps = system.steps.filter((s) => s.opaque);
    if (opaqueSteps.length === 0) continue;
    const name = publicSystemName(system, "css");
    lines.push(`  /* ${system.system} (${system.algorithm}) */`);
    for (const step of opaqueSteps) {
      lines.push(`  --color-${name}-${step.publicStep}: ${step.css};`);
    }
  }
  if (resolved.statics.length > 0) {
    lines.push("  /* statics */");
    for (const s of resolved.statics) {
      lines.push(`  --color-${s.name}: ${s.hex};`);
    }
  }
  lines.push("}", "");

  resolved.modes.forEach((mode, i) => {
    lines.push(i === 0 ? ":root {" : `.${mode} {`);
    for (const role of resolved.roles) {
      lines.push(
        `  --${cssVarName(role)}: ${cssValueFor(resolved, role.perMode[i])};`,
      );
    }
    lines.push("}", "");
  });

  if (format === "tailwind") {
    lines.push(
      "/* Semantic tokens wired into Tailwind utilities */",
      "@theme inline {",
    );
    for (const role of resolved.roles) {
      const name = cssVarName(role);
      lines.push(`  --color-${name}: var(--${name});`);
    }
    lines.push("}");
  }
  while (lines[lines.length - 1] === "") lines.pop();
  return lines.join("\n") + "\n";
}

/**
 * DTCG, for a courier that replays the system into a design tool. Two
 * conventions carry the weight:
 *
 * `$description` is identity, not documentation. A role's is its internal
 * path, which `alias` and `omit` never touch. A demand-driven step's is the
 * roles that demand it, which survives renumbering the coordinate. The
 * description syncs into the tool's own description field, where tree
 * position is invisible — so the redundancy is the point.
 *
 * `$extensions` holds the recipe, which is exactly the volatile part.
 */
const DTCG_NS = "com.fifthrevision.dtg";

export function emitDtcg(resolved: ResolvedDefinition): unknown {
  const lineage = buildLineage(resolved);
  const meta: Record<string, unknown> = { modes: resolved.modes };
  if (resolved.changelog.length > 0) meta.changelog = resolved.changelog;

  const out: Record<string, unknown> = {
    $description: "Generated by dtg from the definition file — do not edit.",
    $extensions: { [DTCG_NS]: meta },
  };

  // Sections seeded up front so every one carries its collection name,
  // aliased or not, in a deterministic order.
  for (const section of resolved.sections) {
    if (section.name === "systems") {
      throw new Error(
        `section "systems" collides with the DTCG primitives group — alias the section`,
      );
    }
    out[section.name] = {
      $extensions: {
        [DTCG_NS]: {
          collection: aliasedName(section.alias, "figma", section.name),
        },
      },
    };
  }

  const systems: Record<string, unknown> = {
    $extensions: {
      [DTCG_NS]: {
        collection: aliasedName(resolved.systemsAlias, "figma", "systems"),
      },
    },
  };
  for (const system of resolved.systems) {
    const steps = system.steps.filter((s) => s.opaque);
    if (steps.length === 0) continue;
    const group: Record<string, unknown> = {};
    for (const step of steps) {
      const ext: Record<string, unknown> = {
        name: `${publicSystemName(system, "figma")}/${step.publicStep}`,
        ref: `${system.system}/${step.selector}`,
        algorithm: system.algorithm,
      };
      if (step.overridden) ext.generated = step.generatedCss;
      group[step.publicStep] = {
        $type: "color",
        $value: dtcgColor(step.css),
        $description: stepIdentity(lineage, system, step),
        $extensions: { [DTCG_NS]: ext },
      };
    }
    systems[system.system] = group;
  }
  if (resolved.statics.length > 0) {
    const group: Record<string, unknown> = {};
    for (const s of resolved.statics) {
      group[s.name] = {
        $type: "color",
        $value: s.hex,
        $description: `static.${s.name}`,
        $extensions: { [DTCG_NS]: { name: `static/${s.name}` } },
      };
    }
    systems.static = group;
  }
  out.systems = systems;

  for (const role of resolved.roles) {
    const section = (out[role.section] ??= {}) as Record<string, unknown>;
    const domain = (section[role.domain] ??= {}) as Record<string, unknown>;
    domain[role.role] = {
      $type: "color",
      $value: dtcgRef(resolved, role.perMode[0]),
      $description: `${role.domain}.${role.role}`,
      $extensions: {
        [DTCG_NS]: {
          name: publicRoleName(role, "figma", "/"),
          modes: Object.fromEntries(
            resolved.modes.map((m, i) => [m, dtcgRef(resolved, role.perMode[i])]),
          ),
          refs: Object.fromEntries(
            resolved.modes.map((m, i) => [m, role.perMode[i].ref]),
          ),
        },
      },
    };
  }

  return out;
}

/** DTCG colors are hex; translucent values take the 8-digit form. */
function dtcgColor(css: string): string {
  const m =
    /^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)$/.exec(
      css,
    );
  if (!m) return css;
  const byte = (n: number) =>
    Math.max(0, Math.min(255, Math.round(n)))
      .toString(16)
      .padStart(2, "0");
  const alpha = m[4] == null ? 1 : Number(m[4]);
  return `#${byte(Number(m[1]))}${byte(Number(m[2]))}${byte(Number(m[3]))}${
    alpha >= 1 ? "" : byte(alpha * 255)
  }`;
}

function stepIdentity(
  lineage: Lineage,
  system: ResolvedSystem,
  step: ResolvedStep,
): string {
  const uses = lineage.get(`${system.system}/${step.selector}`) ?? [];
  if (uses.length === 0) return `${system.system}/${step.selector}`;
  return uses
    .map((u) => `${u.domain}.${u.role}[${u.mode}]`)
    .join(", ");
}

function dtcgRef(resolved: ResolvedDefinition, entry: ResolvedRef): string {
  if (entry.target.kind === "role") {
    const target = resolved.roles.find(
      (r) =>
        entry.target.kind === "role" &&
        r.domain === entry.target.domain &&
        r.role === entry.target.role,
    );
    if (target) return `{${target.section}.${target.domain}.${target.role}}`;
  }
  if (entry.target.kind === "step" && entry.opaque) {
    const system = resolved.systems.find(
      (s) => entry.target.kind !== "role" && s.system === entry.target.system,
    );
    const step = system?.steps.find(
      (s) => entry.target.kind !== "role" && s.selector === entry.target.selector,
    );
    if (system && step) return `{systems.${system.system}.${step.publicStep}}`;
  }
  return dtcgColor(entry.css);
}
